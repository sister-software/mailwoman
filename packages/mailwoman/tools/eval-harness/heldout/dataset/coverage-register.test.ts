import { describe, expect, it } from "vitest"

import {
	buildCoverageRegister,
	renderCoverageRegisterMarkdown,
} from "#tools/eval-harness/heldout/dataset/coverage-register"
import { buildHeldoutDatasetManifest } from "#tools/eval-harness/heldout/dataset/manifest"
import type { HeldoutRow } from "#tools/eval-harness/heldout/per/country"
import { validateReleaseSpec } from "#tools/eval-harness/release/requirements"

const row = (sourceID: string, country: string, source: string, group = sourceID): HeldoutRow => ({
	raw: "12 Main St",
	span_starts: [0],
	span_ends: [2],
	span_tags: ["house_number"],
	country,
	source,
	source_id: sourceID,
	group,
})

const dataset = buildHeldoutDatasetManifest({
	datasetID: "heldout-fixture",
	createdAt: "2026-10-20T00:00:00.000Z",
	drawnFrom: {
		manifest: "/data/MANIFEST.json",
		sha256: "a".repeat(64),
		corpusVersion: "v0.8.0-fixture",
		files: [],
	},
	sampling: {
		method: "per-record-id-country-kind-hash-order",
		perCountry: 10,
		seed: null,
		order: "hash(raw)",
		engine: "duckdb",
	},
	cells: [
		{ country: "US", kind: "address", available: 900, sampled: 3 },
		{ country: "MT", kind: "address", available: 2, sampled: 1 },
		{ country: "IS", kind: "gazetteer", available: 5, sampled: 1 },
	],
	rows: [
		row("u1", "US", "oa-us"),
		row("u1~lower", "US", "oa-us", "u1"),
		row("u2", "US", "usgov-nad"),
		row("m1", "MT", "osm-mt"),
		row("i1", "IS", "wof-admin"),
	],
	rowsFilePath: "fixture.rows.jsonl",
})

const spec = validateReleaseSpec({
	schemaVersion: 3,
	specVersion: "fixture-1",
	rationale: "fixture",
	requirements: [
		{
			id: "us",
			kind: "country",
			country: "US",
			reason: "served market",
			minimum: null,
		},
		{
			id: "is",
			kind: "country",
			country: "IS",
			reason: "fixture: required with no address rows",
			minimum: null,
		},
		{
			id: "nz",
			kind: "country",
			country: "NZ",
			reason: "fixture: required with no test rows at all",
			minimum: null,
		},
	],
	objective: { countries: ["US", "IS"], minimumImprovement: null },
	identities: {
		dataset: { id: null, sha256: null },
		scorer: { id: "exact-parse", revision: "x" },
		inference: { description: "fixture", options: {} },
		published: { description: "p", sha256: null },
		candidate: { description: "c", sha256: null },
	},
	statistics: {
		confidenceLevel: null,
		multipleComparison: "bonferroni",
		samplingUnit: "group",
		rowsIndependent: false,
		groupingAssumption: "fixture",
		requiredPrecision: null,
	},
	provenance: { admitted: { minimum: [], comparative: [] } },
	evaluations: {
		development: { id: null, description: "fixture" },
		confirmation: { id: null, description: "fixture" },
	},
})

describe("buildCoverageRegister", () => {
	it("reports insufficient evidence for a required country with no rows, never zero", () => {
		const register = buildCoverageRegister({ dataset, spec })
		const byCountry = new Map(register.rows.map((r) => [r.country, r]))

		expect([...byCountry.keys()]).toEqual(["IS", "MT", "NZ", "US"])

		for (const country of ["NZ", "IS"]) {
			const entry = byCountry.get(country)!

			expect(entry.status).toBe("required")
			expect(entry.addresses.sampled).toBe(0)
			expect(entry.groups).toBeNull()
			expect(entry.sources).toBeNull()
			expect(entry.provenance).toBeNull()
			expect(entry.evaluation.status).toBe("insufficient_evidence")
		}

		expect(byCountry.get("IS")!.places).toEqual({ available: 5, sampled: 1 })
		expect(byCountry.get("MT")!.status).toBe("experimental")
		expect(byCountry.get("MT")!.evaluation.status).toBe("unqualified")

		const us = byCountry.get("US")!

		expect(us).toMatchObject({
			status: "required",
			objective: true,
			groups: 2,
			provenance: null,
		})

		expect(us.sources).toEqual({ "oa-us": 2, "usgov-nad": 1 })
		expect(us.evaluation.status).toBe("not_evaluated")

		const markdown = renderCoverageRegisterMarkdown(register, "node coverage-register.run.ts --dataset fixture.json")

		expect(markdown).toMatch(/^\| NZ \| required \| 0 \| 0 \| insufficient evidence \|/mu)

		expect(markdown).toContain(
			"Generated by packages/mailwoman/tools/eval-harness/heldout/dataset/coverage-register.run.ts"
		)
	})

	it("counts provenance classes from an audit and reads the verdict's check for a required country", () => {
		const register = buildCoverageRegister({
			dataset,
			spec,
			provenance: {
				source: "audit.json",
				rows: {
					"oa-us:u1": { provenance: "known_overlap", evidence: "e" },
					"usgov-nad:u2": { provenance: "verified_unseen", evidence: "e" },
				},
			},
			verdict: {
				specVersion: "fixture-1",
				outcome: "insufficient_evidence",
				reasons: [],
				inference: { rule: null, rowsByWeightsLocale: {} },
				checks: [
					{
						id: "us",
						check: "minimum",
						threshold: null,
						rows: 3,
						groups: 2,
						estimate: 1,
						publishedEstimate: 1,
						lower: null,
						upper: null,
						method: "clopper_pearson_design_effect",
						effectiveRows: null,
						degreesOfFreedom: null,
						degenerateStrata: [],
						outcome: "insufficient_evidence",
						reasons: ["threshold unregistered"],
					},
				],
				provenance: [],
				statistics: {
					confidenceLevel: null,
					method: "bonferroni",
					simultaneousChecks: 1,
					percentile: null,
					rowsIndependent: false,
					grouping: "metadata",
					groupingAssumption: "fixture",
				},
				artifacts: { published: "p", candidate: "c" },
			},
		})

		const us = register.rows.find((r) => r.country === "US")!

		// The audit's rows map omits one row, and that row counts as unknown.
		expect(us.provenance).toEqual({
			verified_unseen: 1,
			unseen_by_candidate: 0,
			known_overlap: 1,
			unknown: 1,
		})

		expect(us.evaluation).toEqual({
			status: "insufficient_evidence",
			reasons: ["us: insufficient_evidence (threshold unregistered)"],
		})
	})

	it("refuses a verdict for another specification version", () => {
		expect(() =>
			buildCoverageRegister({
				dataset,
				spec,
				verdict: { specVersion: "other" } as Parameters<typeof buildCoverageRegister>[0]["verdict"],
			})
		).toThrow(/spec other/u)
	})
})
