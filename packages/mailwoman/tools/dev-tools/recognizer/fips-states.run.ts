/**
 * Writes the FIPS codes of the states and territories into the `identifiers` family's
 * validator: `packages/recognizer/crates/recognize-core/src/validators/us_state_fips.rs`.
 *
 * The `CensusGEOID` validator checks the state code of a GEOID against this table.
 * `@mailwoman/recognizer` cannot depend on `@mailwoman/tiger`, which owns the codes as `AdminLevel1Code`,
 * because `tiger` depends on `spatial` and `spatial` on `postcode`, which depends on `recognizer`.
 *
 * This tool lives under `mailwoman`, which depends on all of them, and writes the table as a constant.
 *
 * Usage: `node packages/mailwoman/tools/dev-tools/recognizer/fips-states.run.ts [--check]`
 *
 * `--check` leaves the file as it is and exits non-zero when the committed file differs.
 */

import { readLocalTextFile } from "@mailwoman/core/fs/readers"
import { temporaryDirectory } from "@mailwoman/core/fs/temporary"
import { writeLocalFile } from "@mailwoman/core/fs/writers"
import { workspacePath } from "@mailwoman/core/paths"
import { runFile } from "@mailwoman/core/process"
import { parseArguments } from "@mailwoman/core/scripting/arguments"
import { AdminLevel1Code } from "@mailwoman/tiger/state"

const { values } = parseArguments({ options: { check: { type: "boolean", default: false } } })

const target = workspacePath("recognizer", "crates", "recognize-core", "src", "validators", "us_state_fips.rs")
const codes = [...new Set(Object.values(AdminLevel1Code))].toSorted()

if (codes.some((code) => !/^\d{2}$/u.test(code))) {
	throw new Error("AdminLevel1Code holds a value that is not a two-digit code")
}

const source = `// @generated by \`node packages/mailwoman/tools/dev-tools/recognizer/fips-states.run.ts\`. Do not edit.

/// The two-digit FIPS codes of the fifty states, the District of Columbia and the territories, from \`AdminLevel1Code\`
/// in \`@mailwoman/tiger\`, in ascending order.
pub const US_STATE_FIPS: [&str; ${codes.length}] = [${codes.map((code) => `"${code}"`).join(", ")}];
`

await using scratch = await temporaryDirectory("recognize-fips-")
const scratchFile = `${scratch.path.toString()}/us_state_fips.rs`

await writeLocalFile(source, scratchFile)

await runFile("rustfmt", [
	"--edition",
	"2021",
	"--config-path",
	workspacePath("recognizer", "rustfmt.toml").toString(),
	scratchFile,
])

const formatted = await readLocalTextFile(scratchFile)

if (values.check) {
	const committed = await readLocalTextFile(target).catch(() => null)

	if (committed !== formatted) {
		console.error(`${target} differs from the generator's output`)

		process.exitCode = 1
	}
} else {
	await writeLocalFile(formatted, target)

	console.log(`wrote ${target}: ${codes.length} codes`)
}
