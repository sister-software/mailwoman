/// Lowercase hexadecimal. Hexadecimal text holds only `0-9a-f`, so a generated module never spells a word the
/// repository's vocabulary census bans, which base64 text can by chance.
pub fn hex(bytes: &[u8]) -> String {
	bytes.iter().map(|byte| format!("{byte:02x}")).collect()
}

