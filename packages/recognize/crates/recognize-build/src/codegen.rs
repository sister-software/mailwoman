//! Code generation from a family's declarations: the Rust module `recognize-core` compiles, the TypeScript module and
//! artifact module the package ships.
//!
//! Every output derives from [`Declarations`], which also yields the declarations hash, so the Rust declarations, the
//! TypeScript declarations and the artifact's embedded hash agree by construction. The TypeScript is laid out for
//! the repository's formatter, which the generate tool runs over it.

use std::fmt::Write;

use recognize_core::declarations::{kind_name, Declarations};
use recognize_core::ir::CaptureType;

const GENERATED: &str = "@generated by `node packages/recognize/tools/generate.run.ts`. Do not edit.";

fn capture_type_name(kind: CaptureType) -> &'static str {
	match kind {
		CaptureType::Text => "Text",
		CaptureType::Integer => "Integer",
		CaptureType::Decimal => "Decimal",
	}
}

/// Refuses a capture path a flat payload cannot hold.
fn check_flat(declarations: &Declarations) -> Result<(), String> {
	for shape in &declarations.shapes {
		for capture in &shape.captures {
			if capture.path.contains('.') {
				return Err(format!(
					"shape `{}` declares the capture `{}`; payload fields are flat, so a capture path has one segment",
					shape.id, capture.path
				));
			}
		}
	}

	Ok(())
}

/// The family's module name: its ID with dots as underscores.
pub fn module_name(family: &str) -> String {
	family.replace('.', "_")
}

/// The body of `recognize-core/src/declared/<family>.rs`.
pub fn rust_family(declarations: &Declarations) -> Result<String, String> {
	check_flat(declarations)?;

	let mut out = format!(
		"// {GENERATED}\n\ncrate::declare_family! {{\n\tfamily: \"{}\",\n\tdeclarations_hash: \"{}\",\n\tshapes: {{\n",
		declarations.family,
		declarations.hash()
	);

	for shape in &declarations.shapes {
		let captures: Vec<String> = shape
			.captures
			.iter()
			.map(|capture| format!("{}: {}", capture.path, capture_type_name(capture.kind)))
			.collect();

		let spec = match (&shape.validator, captures.is_empty()) {
			(None, true) => "none".to_string(),
			(None, false) => format!("{{\n\t\t\tcaptures: [{}],\n\t\t}}", captures.join(", ")),
			(Some(validator), true) => format!("{{\n\t\t\tvalidator: {validator},\n\t\t}}"),
			(Some(validator), false) => format!(
				"{{\n\t\t\tcaptures: [{}],\n\t\t\tvalidator: {validator},\n\t\t}}",
				captures.join(", ")
			),
		};

		writeln!(out, "\t\t{} = \"{}\" => {spec},", shape.kind, shape.id).expect("a string accepts writes");
	}

	out.push_str("\t}\n}\n");

	Ok(out)
}

/// The body of `recognize-core/src/declared.rs`: the module list and the unions over every declared family.
pub fn rust_declared(all: &[Declarations]) -> String {
	let mut modules: Vec<(String, String)> = all
		.iter()
		.map(|declarations| (module_name(&declarations.family), kind_name(&declarations.family)))
		.collect();

	modules.sort();

	let list = |template: &dyn Fn(&str, &str) -> String| -> String {
		modules
			.iter()
			.map(|(module, variant)| template(module, variant))
			.collect::<Vec<_>>()
			.join("")
	};
	let mut out = format!("// {GENERATED}\n\n");

	for (module, _) in &modules {
		writeln!(out, "pub mod {module};").expect("a string accepts writes");
	}

	out.push_str("\nuse crate::captures::Captures;\nuse crate::recognition::Rejection;\n\n");
	writeln!(
		out,
		"/// The families this crate holds declarations for, in ID order.\npub const FAMILIES: [&str; {}] = [{}];\n",
		modules.len(),
		modules
			.iter()
			.map(|(module, _)| format!("{module}::FAMILY"))
			.collect::<Vec<_>>()
			.join(", ")
	)
	.expect("a string accepts writes");

	out.push_str("/// The closed kind of a shape of any family this crate declares.\n");
	out.push_str("#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]\npub enum Kind {\n");
	out.push_str(&list(&|module, variant| {
		format!("\t{variant}({module}::RecognitionKind),\n")
	}));
	out.push_str("}\n\nimpl Kind {\n");
	out.push_str("\t/// The ID of the family the kind belongs to.\n\tpub const fn family(self) -> &'static str {\n\t\tmatch self {\n");
	out.push_str(&list(&|module, variant| {
		format!("\t\t\tKind::{variant}(_) => {module}::FAMILY,\n")
	}));
	out.push_str("\t\t}\n\t}\n\n");
	out.push_str(
		"\t/// The shape ID the kind stands for.\n\tpub const fn shape(self) -> &'static str {\n\t\tmatch self {\n",
	);
	out.push_str(&list(&|_, variant| {
		format!("\t\t\tKind::{variant}(kind) => kind.shape(),\n")
	}));
	out.push_str("\t\t}\n\t}\n\n");
	out.push_str(
		"\t/// Whether the shape declares a validator.\n\tpub const fn validated(self) -> bool {\n\t\tmatch self {\n",
	);
	out.push_str(&list(&|_, variant| {
		format!("\t\t\tKind::{variant}(kind) => kind.validated(),\n")
	}));
	out.push_str("\t\t}\n\t}\n}\n\n");

	out.push_str("/// The typed payload of a validated shape of any declared family.\n#[derive(Clone, Debug, PartialEq)]\npub enum Payload {\n");
	out.push_str(&list(&|module, variant| format!("\t{variant}({module}::Payload),\n")));
	out.push_str("}\n\nimpl serde::Serialize for Payload {\n");
	out.push_str(
		"\tfn serialize<S: serde::Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {\n\t\tmatch self {\n",
	);
	out.push_str(&list(&|_, variant| {
		format!("\t\t\tPayload::{variant}(payload) => payload.serialize(serializer),\n")
	}));
	out.push_str("\t\t}\n\t}\n}\n\n");

	out.push_str("/// The kind of a shape, or `None` when this crate holds no declarations for the family or the family declares no such\n/// shape.\n");
	out.push_str("pub fn kind(family: &str, shape: &str) -> Option<Kind> {\n\tmatch family {\n");
	out.push_str(&list(&|module, variant| {
		format!("\t\t{module}::FAMILY => {module}::RecognitionKind::from_shape(shape).map(Kind::{variant}),\n")
	}));
	out.push_str("\t\t_ => None,\n\t}\n}\n\n");

	out.push_str("/// The declarations hash this crate was built with for a family, or `None` for a family it holds no declarations for.\n");
	out.push_str("pub fn declarations_hash(family: &str) -> Option<&'static str> {\n\tmatch family {\n");
	out.push_str(&list(&|module, _| {
		format!("\t\t{module}::FAMILY => Some({module}::DECLARATIONS_HASH),\n")
	}));
	out.push_str("\t\t_ => None,\n\t}\n}\n\n");

	out.push_str(
		"/// Runs a kind's validator over the captures of its span. `None` means the shape declares no validator.\n",
	);
	out.push_str(
		"pub fn bind(kind: Kind, captures: &Captures<'_>) -> Option<Result<Payload, Rejection>> {\n\tmatch kind {\n",
	);
	out.push_str(&list(&|module, variant| {
		format!("\t\tKind::{variant}(kind) => {module}::bind(kind, captures).map(|result| result.map(Payload::{variant})),\n")
	}));
	out.push_str("\t}\n}\n");

	out
}

/// `coordinates` as `Coordinates`, and `a.b` as `AB`.
fn pascal(family: &str) -> String {
	kind_name(family)
}

/// `coordinates` as `COORDINATES`.
fn upper_snake(family: &str) -> String {
	family.replace('.', "_").to_ascii_uppercase()
}

/// `coordinates` as `coordinates`, and `a.b` as `aB`.
fn camel(family: &str) -> String {
	let pascal = pascal(family);
	let mut characters = pascal.chars();

	match characters.next() {
		Some(first) => first.to_ascii_lowercase().to_string() + characters.as_str(),
		None => String::new(),
	}
}

fn payload_type(kind: CaptureType) -> &'static str {
	match kind {
		CaptureType::Text => "string",
		CaptureType::Integer => "Validated.Integer",
		CaptureType::Decimal => "Validated.Decimal",
	}
}

/// The body of `lib/<family>.generated.ts`.
pub fn typescript_family(declarations: &Declarations) -> Result<String, String> {
	check_flat(declarations)?;

	let family = pascal(&declarations.family);
	let upper = upper_snake(&declarations.family);
	let uses_brands = declarations.shapes.iter().any(|shape| {
		shape.validator.is_some() && shape.captures.iter().any(|capture| capture.kind != CaptureType::Text)
	});
	let mut out = String::new();

	writeln!(
		out,
		"// SPDX-FileCopyrightText: Teffen Ellis and Mailwoman contributors"
	)
	.unwrap();
	writeln!(
		out,
		"// SPDX-License-Identifier: AGPL-3.0-only OR LicenseRef-Commercial\n"
	)
	.unwrap();
	writeln!(
		out,
		"/**\n * The declarations of the `{}` family: its kinds, its payload types\n * and the hash its artifact embeds.\n *\n * Generated by tools/generate.run.ts from data/ir/{}.json.\n * Edit the grammar or the generator and not this file.\n */\n",
		declarations.family, declarations.family
	)
	.unwrap();

	writeln!(
		out,
		"import {{ {}Artifact }} from \"#artifacts/{}.generated\"",
		camel(&declarations.family),
		declarations.family
	)
	.unwrap();
	writeln!(out, "import {{ defineFamily }} from \"#family\"").unwrap();

	if uses_brands {
		writeln!(out, "import type {{ Validated }} from \"#types\"").unwrap();
	}

	writeln!(out).unwrap();

	writeln!(
		out,
		"/**\n * The family's ID.\n */\nexport const {upper}_FAMILY_ID = \"{}\"\n",
		declarations.family
	)
	.unwrap();
	writeln!(
		out,
		"/**\n * The hash of the generated declarations.\n *\n * The artifact embeds the same value, and the loader refuses an artifact whose hash differs.\n */\nexport const {upper}_DECLARATIONS_HASH =\n\t\"{}\"\n",
		declarations.hash()
	)
	.unwrap();

	writeln!(out, "/**\n * Every kind of recognition the family reports, by name.\n * Each value is the shape's ID.\n */\nexport const {family}Kind = {{").unwrap();

	for shape in &declarations.shapes {
		writeln!(out, "\t{}: \"{}\",", shape.kind, shape.id).unwrap();
	}

	writeln!(out, "}} as const\n").unwrap();
	writeln!(
		out,
		"export type {family}Kind = (typeof {family}Kind)[keyof typeof {family}Kind]\n"
	)
	.unwrap();

	for shape in declarations.shapes.iter().filter(|shape| shape.validator.is_some()) {
		writeln!(
			out,
			"/**\n * The validated payload of `{}`.\n */\nexport interface {}Payload {{",
			shape.id, shape.kind
		)
		.unwrap();

		for capture in &shape.captures {
			writeln!(out, "\treadonly {}: {}", capture.path, payload_type(capture.kind)).unwrap();
		}

		writeln!(out, "}}\n").unwrap();
	}

	let validated: Vec<_> = declarations
		.shapes
		.iter()
		.filter(|shape| shape.validator.is_some())
		.collect();
	let docs = "/**\n * The payload of each kind that declares a validator.\n * A kind with no entry has its span and text only.\n */";

	if validated.is_empty() {
		writeln!(out, "{docs}\nexport type {family}Payloads = Record<never, never>").unwrap();
	} else {
		writeln!(out, "{docs}\nexport interface {family}Payloads {{").unwrap();

		for shape in validated {
			writeln!(out, "\treadonly \"{}\": {}Payload", shape.id, shape.kind).unwrap();
		}

		writeln!(out, "}}").unwrap();
	}

	writeln!(
		out,
		"\n/**\n * The `{id}` family.\n *\n * Pass it to `createRecognizer`.\n * A bundle that imports this module holds this family's artifact and no other,\n * and no engine until a recognizer is created.\n */\nexport const {name} = defineFamily<{family}Kind, {family}Payloads>({{\n\tid: {upper}_FAMILY_ID,\n\tkinds: {family}Kind,\n\tdeclarationsHash: {upper}_DECLARATIONS_HASH,\n\tartifact: {name}Artifact,\n}})",
		id = declarations.family,
		name = camel(&declarations.family),
	)
	.unwrap();

	Ok(out)
}

/// The body of `lib/artifacts/<family>.generated.ts`.
pub fn typescript_artifact(family: &str, artifact: &[u8], sha256: &str) -> String {
	let mut out = String::new();

	writeln!(
		out,
		"// SPDX-FileCopyrightText: Teffen Ellis and Mailwoman contributors"
	)
	.unwrap();
	writeln!(
		out,
		"// SPDX-License-Identifier: AGPL-3.0-only OR LicenseRef-Commercial\n"
	)
	.unwrap();
	writeln!(
		out,
		"/**\n * The compiled `{family}` family, {} bytes,\n * SHA-256 {sha256}.\n *\n * Generated by tools/generate.run.ts from data/artifacts/{family}.rca1.\n * Edit the grammar or the compiler and not this file.\n */\n",
		artifact.len()
	)
	.unwrap();
	writeln!(out, "import {{ decodeHex }} from \"#hex\"\n").unwrap();
	writeln!(out, "const HEX =\n\t\"{}\"\n", hex(artifact)).unwrap();
	writeln!(out, "let decoded: Uint8Array<ArrayBuffer> | undefined\n").unwrap();
	writeln!(
		out,
		"/**\n * The artifact's bytes, decoded on first use.\n */\nexport function {}Artifact(): Uint8Array<ArrayBuffer> {{\n\treturn (decoded ??= decodeHex(HEX))\n}}",
		camel(family)
	)
	.unwrap();

	out
}

/// Lowercase hexadecimal. Hexadecimal text holds only `0-9a-f`, so a generated module never spells a word the
/// repository's vocabulary census bans, which base64 text can by chance.
pub fn hex(bytes: &[u8]) -> String {
	bytes.iter().map(|byte| format!("{byte:02x}")).collect()
}

#[cfg(test)]
mod tests {
	use super::*;

	#[test]
	fn hex_matches_known_vectors() {
		assert_eq!(hex(b""), "");
		assert_eq!(hex(b"f"), "66");
		assert_eq!(hex(&[0, 255, 16]), "00ff10");
	}
}
