/**
 *   Builds `crates/recognizer-wasm` for `wasm32-unknown-unknown` with the release profile the root
 *   `Cargo.toml` documents, and writes `wasm/recognizer.wasm` and `lib/embedded.generated.ts`.
 *
 *   Two flags change that profile for this module.
 *   `-Copt-level=3` replaces the profile's `s`: the search loop is the cost of a call,
 *   and the speed measured 2.5 to 3.6 times faster for 1 KB more binary.
 *
 *   `-Cstrip=symbols` drops the `name` section, 176 KB of the first build, that only a debugger reads.
 *
 *   The module is a C-ABI adapter, so the build needs no tool beyond `cargo`
 *   and the toolchain `rust-toolchain.toml` pins.
 *   That file also installs the `wasm32-unknown-unknown` target.
 *
 *   The `@sister.software/h3` package builds with `wasm-bindgen`, whose CLI
 *   isn't part of this repository's CI.
 *
 *   No optimizer runs on the binary, so the committed bytes are the compiler's bytes.
 *
 *   Host paths that panic messages embed are remapped, so a checkout in any directory builds the same bytes.
 *   A separate target directory keeps the flags from invalidating the shared build cache.
 *
 *   `lib/embedded.generated.ts` holds the binary as hexadecimal text for the
 *   first-call synchronous instantiation.
 *   Hexadecimal text cannot spell a word the repository's vocabulary census bans.
 *
 *   Base64 text can spell one by chance.
 *   The workerd entry imports `wasm/recognizer.wasm` instead.
 *
 *   With `--check`, the tool builds without writing and exits non-zero when either committed file differs.
 *
 *   Usage: `node packages/recognizer/tools/build-wasm.run.ts [--check]`
 */

import { readLocalBuffer, readLocalTextFile } from "@mailwoman/core/fs/readers"
import { replaceFileAtomically, writeLocalFile } from "@mailwoman/core/fs/writers"
import { sha256Hex } from "@mailwoman/core/hash"
import { stringifyJSON } from "@mailwoman/core/json"
import { repoRootPath, workspacePath } from "@mailwoman/core/paths"
import { runFile } from "@mailwoman/core/process"
import { parseArguments } from "@mailwoman/core/scripting/arguments"
import { type FormatConfig, format } from "oxfmt"

const { values } = parseArguments({ options: { check: { type: "boolean", default: false } } })

const targetDirectory = repoRootPath("target", "recognizer-wasm")
const built = `${targetDirectory}/wasm32-unknown-unknown/release/recognizer_wasm.wasm`
const committedBinary = workspacePath("recognizer", "wasm", "recognizer.wasm")
const committedEmbedded = workspacePath("recognizer", "lib", "embedded.generated.ts")

// The compiler embeds this directory in panic locations, so the build reads where the host keeps its registry sources.
// oxlint-disable-next-line sister-software/no-process-globals -- a build tool reads the toolchain's own variables
const cargoHome = process.env["CARGO_HOME"] ?? `${process.env["HOME"] ?? ""}/.cargo`

const rustflags = [
	`--remap-path-prefix=${repoRootPath()}=/mailwoman`,
	`--remap-path-prefix=${cargoHome}=/cargo`,
	"-Cdebuginfo=0",
	// The `name` section lists every function for a debugger.
	// The module needs none of it at run time.
	"-Cstrip=symbols",
	"-Copt-level=3",
]

await runFile(
	"cargo",
	[
		"build",
		"--release",
		"--locked",
		"--target",
		"wasm32-unknown-unknown",
		"-p",
		"recognizer-wasm",
		"--target-dir",
		targetDirectory,
		"--config",
		`build.rustflags=${stringifyJSON(rustflags)}`,
	],
	{ cwd: workspacePath("recognizer") }
)

const binary = await readLocalBuffer(built)
const digest = sha256Hex(binary)

// effect-loads: oxfmt.config.ts
const { default: formatConfig } = (await import(repoRootPath("oxfmt.config.ts").toString())) as {
	default: FormatConfig
}

const copyrightLine = "// SPDX-FileCopyrightText: Teffen Ellis and Mailwoman contributors"
const licenseLine = "// SPDX-License-Identifier: AGPL-3.0-only OR LicenseRef-Commercial"

const embeddedSource = `${copyrightLine}
${licenseLine}

/**
 *   The recognizer engine binary as hexadecimal text.
 *
 *   Size: ${binary.length} bytes.
 *   SHA-256: ${digest}.
 *
 *   Generated by tools/build-wasm.run.ts from wasm/recognizer.wasm.
 *   Edit the crate and not this file.
 *
 *   The default entry decodes it on the first call.
 *   A bundle of one family never imports it.
 */

import { decodeHex } from "#hex"

const HEX = "${binary.toString("hex")}"

/**
 * Decodes the embedded engine binary.
 */
export function embeddedWasmBytes(): Uint8Array<ArrayBuffer> {
	return decodeHex(HEX)
}
`

const formatted = await format(committedEmbedded.toString(), embeddedSource, formatConfig)

if (formatted.errors.length) {
	throw new Error(
		`oxfmt could not format the embedded module: ${formatted.errors.map((error) => error.message).join("; ")}`
	)
}

if (values.check) {
	const committed = await readLocalBuffer(committedBinary).catch(() => null)
	const embedded = await readLocalTextFile(committedEmbedded).catch(() => null)

	if (committed && committed.equals(binary)) {
		console.log(`wasm/recognizer.wasm matches the build: ${digest} (${binary.length} bytes)`)
	} else {
		console.error(
			`wasm/recognizer.wasm is stale: committed ${committed ? sha256Hex(committed) : "absent"}, built ${digest} (${binary.length} bytes)`
		)

		process.exitCode = 1
	}

	if (embedded !== formatted.code) {
		console.error("lib/embedded.generated.ts differs from the build")

		process.exitCode = 1
	}
} else {
	await replaceFileAtomically(built, committedBinary)
	await writeLocalFile(formatted.code, committedEmbedded)

	console.log(`wrote wasm/recognizer.wasm and lib/embedded.generated.ts: ${digest} (${binary.length} bytes)`)
}
