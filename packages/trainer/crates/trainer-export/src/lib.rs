//! Exports a Mailwoman coarse-encoder checkpoint to ONNX and quantizes the graph to int8 without Python.
//!
//! The export reads a checkpoint directory as `MailwomanCoarseEncoder.save_pretrained` writes it, `config.json`
//! beside `pytorch_model.bin`, and writes the opset-17 graph that
//! `corpus-python/src/mailwoman_train/export/onnx.py` writes through `torch.onnx.export(dynamo=True)` with
//! torch 2.12.0 and onnxscript 0.7.2. The graph's inputs, outputs, declared dimensions and computation follow that
//! exporter's. Node names and file bytes do not.
//!
//! The char path (`use_char_embed`) exports behind `char_ids` and `attention_mask`, as
//! `export_to_onnx(char_window=…)` does. `split` moves the int8 graph's token-embedding table into the `MWE1` row
//! files the browser runtime reads by range.
//!
//! The quantizer reproduces `onnxruntime.quantization.quantize_dynamic(weight_type=QuantType.QInt8)` from
//! onnxruntime 1.30.0 with that function's defaults, after the stale-`value_info` strip that
//! `corpus-python/src/mailwoman_train/export/quantize.py` applies first.

pub mod checkpoint;
pub mod config;
pub mod export;
pub mod graph;
pub mod pickle;
pub mod quantize;
pub mod shape;
pub mod split;

/// The ONNX message types, generated by prost from `proto/onnx.proto`.
#[allow(clippy::all, missing_docs)]
pub mod onnx {
	include!(concat!(env!("OUT_DIR"), "/onnx.rs"));
}

/// An export or quantization failure, with the message that names what could not be read or built.
#[derive(Debug)]
pub struct Error(pub String);

impl std::fmt::Display for Error {
	fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
		f.write_str(&self.0)
	}
}

impl std::error::Error for Error {}

impl From<std::io::Error> for Error {
	fn from(error: std::io::Error) -> Self {
		Error(error.to_string())
	}
}

impl From<prost::DecodeError> for Error {
	fn from(error: prost::DecodeError) -> Self {
		Error(format!("ONNX decode: {error}"))
	}
}

pub type Result<T> = std::result::Result<T, Error>;

/// Builds an [`Error`] from a format string.
#[macro_export]
macro_rules! fail {
	($($arg:tt)*) => {
		$crate::Error(format!($($arg)*))
	};
}
