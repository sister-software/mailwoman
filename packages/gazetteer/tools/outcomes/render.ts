import { repoRootPath } from "@mailwoman/core/paths"
import { orderedJSON } from "@mailwoman/core/values/json"

import type { CompiledOutcomeSpec, OutcomeSpecPin } from "#whosonfirst/outcomes/spec"

/**
 * The repository path of the generated module, relative to the repository root.
 */
export const OUTCOME_KINDS_MODULE = "packages/gazetteer/lib/whosonfirst/outcomes/kinds.ts"

/**
 * The absolute path of the generated module.
 */
export function outcomeKindsModulePath(): string {
	return repoRootPath(OUTCOME_KINDS_MODULE)
}

/**
 * One row of the generated `OUTCOME_KINDS` table.
 */
export interface OutcomeKindRow {
	id: number
	parent: string | null
	facet: string
	status: string
	supersededBy: string | null
	defaultFor: string[]
}

/**
 * The generated table's rows for one compiled spec, keyed by name in `mw:id` order.
 */
export function outcomeKindRows(spec: CompiledOutcomeSpec): Map<string, OutcomeKindRow> {
	return new Map(
		spec.definitions.map((definition) => [
			definition["mw:name"],
			{
				id: definition["mw:id"],
				parent: definition["mw:parent"],
				facet: definition["mw:facet"],
				status: definition["mw:status"],
				supersededBy: definition["mw:superseded_by"],
				defaultFor: definition["mw:default_for"].toSorted(),
			},
		])
	)
}

/**
 * The text of `packages/gazetteer/lib/whosonfirst/outcomes/kinds.ts` for one
 * compiled spec, before `oxfmt` formats it.
 */
export function renderOutcomeKindsModule(spec: CompiledOutcomeSpec, pin: OutcomeSpecPin): string {
	const table = outcomeKindRows(spec)

	return [
		"// SPDX-FileCopyrightText: Teffen Ellis and Mailwoman contributors",
		"// SPDX-License-Identifier: AGPL-3.0-only OR LicenseRef-Commercial",
		"",
		"/**",
		" * This file was generated by: node packages/gazetteer/tools/outcomes/compile.run.ts",
		" *",
		" * It is the compiled outcome vocabulary of `mailwoman/whosonfirst-outcomes` at the pinned revision.",
		" * The `outcome-kinds` repository check compares it with the clone's compiled spec.",
		" */",
		"",
		"/**",
		" * The definitions revision and the SHA-256 of its `data/outcomes-spec-latest.json`.",
		" */",
		`export const OUTCOME_DEFINITIONS_PIN = ${orderedJSON(pin, { indent: "\t" })} as const`,
		"",
		"/**",
		" * Every outcome kind, keyed by its stable name, in `mw:id` order.",
		" *",
		" * `id` is the definitions registry's number, `defaultFor` the placetypes whose",
		" * records hold the kind by default.",
		" */",
		`export const OUTCOME_KINDS = ${orderedJSON(table, { indent: "\t" })} as const`,
		"",
		"/**",
		" * The name of one outcome kind, such as `natural.mountain`.",
		" */",
		"export type OutcomeKind = keyof typeof OUTCOME_KINDS",
		"",
	].join("\n")
}
