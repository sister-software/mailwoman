/**
 *   Compiles the normalized data into RGY1 artifacts with `crates/registry-build`, writes each artifact as a
 *   TypeScript module under `lib/artifacts/`, and records every artifact's SHA-256 in `data/manifests/artifacts.json`.
 *
 *   Each artifact is its own module exporting one lazily decoded getter, so a bundle that imports the collision
 *   predicate holds the collision bitset and no airport record. The fixture profile under `test/fixtures/` is compiled
 *   too, into `test/fixtures/artifacts/*.rgy1`, so the committed fixtures stay equal to the compiler's output.
 *
 *   Usage: `node packages/registry/tools/generate.run.ts [--check]`
 *
 *   `--check` compiles without writing and exits non-zero when a generated module or manifest differs.
 */

import { readLocalBuffer, readLocalJSONFile } from "@mailwoman/core/fs/readers"
import { temporaryDirectory } from "@mailwoman/core/fs/temporary"
import { writeLocalFile } from "@mailwoman/core/fs/writers"
import { sha256File } from "@mailwoman/core/hash"
import { prettyJSON } from "@mailwoman/core/json"
import { repoRootPath, workspacePath } from "@mailwoman/core/paths"
import { runFile } from "@mailwoman/core/process"
import { parseArguments } from "@mailwoman/core/scripting/arguments"

import { artifactModulePath } from "#tools/artifact-path"

const { values } = parseArguments({ options: { check: { type: "boolean", default: false } } })
const registry = (...segments: string[]): string => workspacePath("registry", ...segments)

const ARTIFACTS = [
	"iso3166-1-alpha2-membership",
	"iso3166-1-alpha3-membership",
	"iso3166-1-records",
	"iata-airport-membership",
	"iata-airport-records",
	"country-airport-collision",
] as const

const camel = (name: string): string =>
	name.replaceAll(/-(\w)/g, (_, letter: string) => letter.toUpperCase()).replace(/^(\d)/, "_$1")

await runFile("cargo", ["build", "--release", "--locked", "-p", "registry-build"], { cwd: workspacePath("registry") })

const binary = repoRootPath("target", "release", "registry-build")

async function compileProfile(normalized: string, lock: string, out: string): Promise<void> {
	await runFile(binary, [`${normalized}/iso3166-1.json`, `${normalized}/iata-airports.json`, lock, out])
}

await using scratch = await temporaryDirectory("registry-generate-")
const openOut = scratch.path.toString()
const profile = await readLocalJSONFile<{ profile: string }>(registry("data", "manifests", "sources.lock.json"))

await compileProfile(registry("data", "normalized"), registry("data", "manifests", "sources.lock.json"), openOut)

let stale = 0

async function emit(path: string, content: string | Uint8Array): Promise<void> {
	if (values.check) {
		const current = await readLocalBuffer(path).catch(() => null)
		const next = typeof content === "string" ? Buffer.from(content) : Buffer.from(content)

		if (!current || !current.equals(next)) {
			console.error(`${path} differs from the generator's output`)

			stale++
		}
	} else {
		await writeLocalFile(content, path)
	}
}

const manifest: Record<string, { sha256: string; bytes: number; profile: string }> = {}

for (const name of ARTIFACTS) {
	const built = `${openOut}/${name}.rgy1`
	const bytes = await readLocalBuffer(built)
	const sha256 = await sha256File(built)
	const getter = `${camel(name)}Artifact`

	manifest[name] = { sha256, bytes: bytes.byteLength, profile: profile.profile }

	const module = `/**
 * @copyright Sister Software
 * @license AGPL-3.0
 * @author Teffen Ellis, et al.
 *
 *   The \`${name}\` artifact of the \`${profile.profile}\` profile, ${bytes.byteLength} bytes, SHA-256 ${sha256}.
 *   Generated by tools/generate.run.ts from data/normalized. Edit the data or the compiler rather than this file.
 */

import { decodeBase64 } from "#rgy1/base64"

const BASE64 =
	"${bytes.toString("base64")}"

let bytes: Uint8Array | null = null

/**
 * Returns the artifact's bytes, decoded on first call and shared afterwards.
 *
 * Callers read the bytes and never write them.
 */
export function ${getter}(): Uint8Array {
	bytes ??= decodeBase64(BASE64)

	return bytes
}
`

	await emit(registry("lib", "artifacts", `${artifactModulePath(name)}.ts`), module)
}

await emit(registry("data", "manifests", "artifacts.json"), prettyJSON(manifest))

// The fixture profile, committed as bytes so the layout test and the Rust tests read the same artifacts.
const fixtureOut = values.check ? `${openOut}/fixtures` : registry("test", "fixtures", "artifacts")

await compileProfile(
	registry("test", "fixtures", "normalized"),
	registry("test", "fixtures", "normalized", "sources.lock.json"),
	fixtureOut
)

if (values.check) {
	for (const name of ARTIFACTS) {
		const built = await readLocalBuffer(`${fixtureOut}/${name}.rgy1`)
		const committed = await readLocalBuffer(registry("test", "fixtures", "artifacts", `${name}.rgy1`)).catch(() => null)

		if (!committed || !committed.equals(built)) {
			console.error(`test/fixtures/artifacts/${name}.rgy1 differs from the compiler's output`)

			stale++
		}
	}
}

if (stale) {
	process.exitCode = 1
} else {
	for (const [name, entry] of Object.entries(manifest)) {
		console.log(`${name}\t${entry.bytes} bytes\t${entry.sha256}`)
	}
}
